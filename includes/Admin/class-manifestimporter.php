	public function handle_upload(): void {
		$post_id = isset( $_POST['post_id'] ) ? absint( $_POST['post_id'] ) : 0;
		$phase   = isset( $_POST['phase'] ) ? sanitize_key( $_POST['phase'] ) : '';

		if ( ! $post_id || ! check_ajax_referer( 'scsl_import_manifest_' . $post_id, 'nonce', false ) ) {
			wp_send_json_error( __( 'Security check failed.', 'seedcast-sermon-library' ) );
		}

		if ( ! current_user_can( 'edit_post', $post_id ) ) {
			wp_send_json_error( __( 'You do not have permission to edit this post.', 'seedcast-sermon-library' ) );
		}

		if ( empty( $_FILES['zip']['tmp_name'] ) ) {
			wp_send_json_error( __( 'No file received.', 'seedcast-sermon-library' ) );
		}

		// Validate it's a zip
		$file     = $_FILES['zip']; // phpcs:ignore WordPress.Security.ValidatedSanitizedInput
		$tmp_path = $file['tmp_name'];
		$finfo    = new \finfo( FILEINFO_MIME_TYPE );
		$mime     = $finfo->file( $tmp_path );

		if ( ! in_array( $mime, [ 'application/zip', 'application/x-zip-compressed', 'application/octet-stream' ], true ) ) {
			wp_send_json_error( __( 'File must be a .zip archive.', 'seedcast-sermon-library' ) );
		}

		// Extract to temp dir
		$extract_dir = get_temp_dir() . 'scsl_manifest_' . $post_id . '_' . wp_generate_password( 8, false ) . '/';
		wp_mkdir_p( $extract_dir );

		$zip = new \ZipArchive();
		if ( $zip->open( $tmp_path ) !== true ) {
			$this->cleanup( $extract_dir );
			wp_send_json_error( __( 'Could not open zip file.', 'seedcast-sermon-library' ) );
		}
		$zip->extractTo( $extract_dir );
		$zip->close();

		// Find manifest.xml
		$manifest_path = $extract_dir . 'manifest.xml';
		if ( ! file_exists( $manifest_path ) ) {
			$this->cleanup( $extract_dir );
			wp_send_json_error( __( 'No manifest.xml found in zip.', 'seedcast-sermon-library' ) );
		}

		$manifest = $this->parse_manifest( $manifest_path, $extract_dir );
		if ( is_wp_error( $manifest ) ) {
			$this->cleanup( $extract_dir );
			wp_send_json_error( $manifest->get_error_message() );
		}

		if ( $phase === 'preview' ) {
			$this->cleanup( $extract_dir );
			wp_send_json_success( $manifest );
		}

		// Import phase
		$selected  = isset( $_POST['selected'] ) ? json_decode( sanitize_text_field( wp_unslash( $_POST['selected'] ) ), true ) : [];
		$overwrite = ! empty( $_POST['overwrite'] ) && $_POST['overwrite'] === '1';

		if ( ! is_array( $selected ) ) {
			$this->cleanup( $extract_dir );
			wp_send_json_error( __( 'Invalid selection.', 'seedcast-sermon-library' ) );
		}

		$result = $this->import( $post_id, $manifest, $selected, $overwrite );
		$this->cleanup( $extract_dir );

		if ( is_wp_error( $result ) ) {
			wp_send_json_error( $result->get_error_message() );
		}

		wp_send_json_success( [
			'message' => sprintf(
				/* translators: %d number of fields imported */
				__( 'Imported %d fields successfully.', 'seedcast-sermon-library' ),
				$result
			),
		] );
	}

	/**
	 * Parse manifest.xml and load file contents.
	 *
	 * @return array|\WP_Error
	 */
	private function parse_manifest( string $manifest_path, string $extract_dir ) {
		libxml_use_internal_errors( true );
		$xml = simplexml_load_file( $manifest_path );
		if ( ! $xml ) {
			return new \WP_Error( 'bad_xml', __( 'Could not parse manifest.xml.', 'seedcast-sermon-library' ) );
		}

		$meta = [];
		foreach ( $xml->meta->field as $field ) {
			$name        = (string) $field['name'];
			$meta[ $name ] = (string) $field;
		}

		$items = [];
		foreach ( $xml->items->item as $item ) {
			$key      = (string) $item['key'];
			$label    = (string) $item['label'];
			$file     = (string) $item['file'];
			$filepath = $extract_dir . $file;

			if ( file_exists( $filepath ) ) {
				$items[ $key ] = [
					'label'   => $label,
					'content' => $this->read_file( $filepath ),
				];
			}
		}

		return [
			'meta'  => $meta,
			'items' => $items,
		];
	}

	/**
	 * Write manifest data to sermon post meta.
	 *
	 * @return int|\WP_Error Number of fields written.
	 */
	private function import( int $post_id, array $manifest, array $selected, bool $overwrite ) {
		$meta  = $manifest['meta'];
		$items = $manifest['items'];
		$count = 0;

		// Helper: only write if overwrite=true or field is empty
		$write = function( string $key, $value ) use ( $post_id, $overwrite, &$count ) {
			if ( ! $overwrite ) {
				$existing = get_post_meta( $post_id, $key, true );
				if ( ! empty( $existing ) ) return;
			}
			update_post_meta( $post_id, $key, $value );
			$count++;
		};

		// Post title from meta
		if ( ! empty( $meta['title'] ) ) {
			$existing_title = get_post_field( 'post_title', $post_id );
			if ( $overwrite || empty( $existing_title ) || $existing_title === __( 'Auto Draft', 'seedcast-sermon-library' ) ) {
				wp_update_post( [
					'ID'         => $post_id,
					'post_title' => sanitize_text_field( $meta['title'] ),
				] );
				$count++;
			}
		}

		// Primary scripture → focus passage
		if ( ! empty( $meta['primary_scripture'] ) ) {
			$write( '_scsl_focus_passage', sanitize_text_field( $meta['primary_scripture'] ) );
		}

		// Speaker → look up by name
		if ( ! empty( $meta['speaker'] ) ) {
			$speaker = get_posts( [
				'post_type'      => 'scsl_speaker',
				'title'          => $meta['speaker'],
				'posts_per_page' => 1,
				'post_status'    => 'publish',
				'fields'         => 'ids',
			] );
			if ( ! empty( $speaker ) ) {
				$write( '_scsl_speaker_id', absint( $speaker[0] ) );
			}
		}

		// Read from the shared map rather than a local copy. The AI Engine
		// imports the same content from the API and reads the same map, so
		// the two paths cannot produce different sermons from the same
		// generation.
		$key_map = FieldMap::api_to_meta();

		foreach ( $selected as $item_key ) {
			if ( ! isset( $items[ $item_key ] ) ) continue;
			$content = $items[ $item_key ]['content'];

			if ( isset( $key_map[ $item_key ] ) ) {
				$meta_key = $key_map[ $item_key ];
				if ( in_array( $meta_key, FieldMap::plain_text_meta(), true ) ) {
					// Plain text fields: strip tags
					$write( $meta_key, sanitize_textarea_field( wp_strip_all_tags( $content ) ) );
				} else {
					// Rich HTML fields
					$write( $meta_key, wp_kses_post( $content ) );
				}

				// Extract article title from first h2/h3 in article
				if ( $item_key === 'article' ) {
					preg_match( '/<h[23][^>]*>(.*?)<\/h[23]>/i', $content, $heading );
					if ( ! empty( $heading[1] ) ) {
						$write( '_scsl_article_title', sanitize_text_field( wp_strip_all_tags( $heading[1] ) ) );
					}
				}
			}

			// scripture.html → other passages
			if ( $item_key === 'scripture' ) {
				preg_match_all( '/<li>(.*?)<\/li>/i', $content, $matches );
				$passages = [];
				foreach ( $matches[1] as $passage ) {
					$clean = sanitize_text_field( wp_strip_all_tags( $passage ) );
					// Strip "Main: " prefix: that's the focus passage
					$clean = preg_replace( '/^Main:\s*/i', '', $clean );
					if ( $clean ) $passages[] = $clean;
				}
				if ( $passages ) {
					if ( ! $overwrite ) {
						$existing = get_post_meta( $post_id, '_scsl_other_passages', true );
						if ( empty( $existing ) ) {
							update_post_meta( $post_id, '_scsl_other_passages', $passages );
						SermonMeta::sync_scripture( $post_id );
							$count++;
						}
					} else {
						update_post_meta( $post_id, '_scsl_other_passages', $passages );
						SermonMeta::sync_scripture( $post_id );
						$count++;
					}
				}
			}

			// Several fields stack into the single resources body.
			if ( in_array( $item_key, FieldMap::appended_fields(), true ) ) {
				$existing_resources = get_post_meta( $post_id, '_scsl_resources', true ) ?: '';
				$label   = $items[ $item_key ]['label'];
				$section = '<h3>' . esc_html( $label ) . '</h3>' . wp_kses_post( $content );
				if ( $overwrite || strpos( $existing_resources, $label ) === false ) {
					update_post_meta( $post_id, '_scsl_resources', $existing_resources . $section );
					$count++;
				}
			}
		}

		return $count;
	}

	/**
	 * WP_Filesystem, initialised on first use.
	 *
	 * Reading and deleting go through it rather than PHP's own functions so
	 * this works on hosts where WordPress writes over FTP or SSH instead of
	 * touching the disk as the web user.
	 *
	 * @return \WP_Filesystem_Base|null
	 */
	private function filesystem() {
		global $wp_filesystem;

		if ( ! $wp_filesystem ) {
			require_once ABSPATH . 'wp-admin/includes/file.php';
			WP_Filesystem();
		}

		return $wp_filesystem ?: null;
	}

	/**
	 * Read one extracted file.
	 *
	 * @param string $filepath Absolute path inside the extraction directory.
	 * @return string Empty string when the file cannot be read.
	 */
	private function read_file( string $filepath ): string {
		$fs = $this->filesystem();
		if ( ! $fs ) {
			return '';
		}

		$contents = $fs->get_contents( $filepath );

		return false === $contents ? '' : (string) $contents;
	}

	/**
	 * Remove the temporary extraction directory.
	 *
	 * Goes through WP_Filesystem rather than calling rmdir() directly, so it
	 * works on hosts where WordPress writes over FTP or SSH instead of
	 * touching the disk as the web user.
	 */
	private function cleanup( string $dir ): void {
		if ( ! is_dir( $dir ) ) return;

		$fs = $this->filesystem();

		if ( $fs ) {
			// Recursive delete, which handles the files inside as well.
			$fs->delete( $dir, true );
			return;
		}

		// WP_Filesystem could not be initialised, which happens when
		// credentials are needed and none are available. Fall back to removing
		// the files we can, so a temp directory full of an uploaded zip is not
		// left behind.
		$files = new \RecursiveIteratorIterator(
			new \RecursiveDirectoryIterator( $dir, \RecursiveDirectoryIterator::SKIP_DOTS ),
			\RecursiveIteratorIterator::CHILD_FIRST
		);
		foreach ( $files as $file ) {
			if ( ! $file->isDir() ) {
				wp_delete_file( $file->getRealPath() );
			}
		}
	}
