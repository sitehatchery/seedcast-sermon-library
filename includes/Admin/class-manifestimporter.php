	public function register_meta_box(): void {
		// This box is for churches that generate content on seedcast.ai and
		// bring the zip across by hand. With the engine installed and working,
		// the same content arrives on the sermon itself, and offering a second
		// way to do it is just something else to explain.
		if ( defined( 'SCPRO_VERSION' ) && apply_filters( 'scsl_show_manifest_import', false ) === false ) return;

		add_meta_box(
			'scsl_manifest_import',
			__( 'Import Content from Seedcast', 'seedcast-sermon-library' ),
			[ $this, 'render_meta_box' ],
			'scsl_sermon',
			'side',
			'high'
		);
	}

