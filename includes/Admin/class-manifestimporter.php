<?php
/**
 * Manifest Importer
 *
 * Handles upload and processing of Seedcast content manifest zips on the
 * New Sermon screen. Populates sermon fields from the manifest and HTML files.
 *
 * This is the same import contract the AI pipeline will use internally
 * the API generates a manifest zip and this class processes it.
 *
 * @package SeedcastSermonLibrary
 */

namespace SeedcastSermonLibrary\Admin;

use SeedcastSermonLibrary\Import\FieldMap;

if ( ! defined( 'ABSPATH' ) ) exit;

class ManifestImporter {

	public function init(): void {
		add_action( 'add_meta_boxes',         [ $this, 'register_meta_box' ] );
		add_action( 'wp_ajax_scsl_import_manifest', [ $this, 'handle_upload' ] );
	}

	public function register_meta_box(): void {
		// This box is for churches that generate content on seedcast.ai and
		// bring the zip across by hand. With the engine installed and working,
		// the same content arrives on the sermon itself, and offering a second
		// way to do it is just something else to explain.
		if ( defined( 'SCPRO_VERSION' ) && apply_filters( 'scsl_show_manifest_import', false ) === false ) return;

		add_meta_box(
			'scsl_manifest_import',
			__( 'Import Content from Seedcast', 'seedcast-sermon-library' ),
			[ $this, 'render_meta_box' ],
			'scsl_sermon',
			'side',
			'high'
		);
	}

